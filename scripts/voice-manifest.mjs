import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { QUIZ_CARDS, KANA_ROWS, BASIC_KANA } from '../src/data.js';
import { REWARD_TRAINS } from '../src/reward.js';
import { BOOK_TRAINS } from '../src/book-trains.js';
import { questionText, hintText, praiseText, rewardText, tracePromptText, VOICE_SAMPLE } from '../src/voice-lines.js';
const lines = new Map();
const names = { yamanote: '山手線', enoden: '江ノ電', 'doctor-yellow': 'ドクターイエロー', 'narita-express': '成田エクスプレス', marunouchi: '丸ノ内線', rapit: 'ラピート', keikyu: '京急線', sonic: 'ソニック', nemuro: '根室本線', hitachi: 'ひたち', 'heisei-chikuho': '平成筑豊鉄道', yufuin: 'ゆふいんの森', yokosuka: '横須賀線' };
Object.assign(names, { inaho: 'いなほ', 'ueno-tokyo': '上野東京ライン', odoriko: '踊り子', kinugawa: 'きぬがわ', kuroshio: 'くろしお', shiosai: 'しおさい', skyliner: 'スカイライナー', seibu: '西武線', tanigawa: 'たにがわ', chuo: '中央線', tenhama: '天竜浜名湖鉄道', toki: 'とき', nichirin: 'にちりん', numajiri: '沼尻軽便鉄道', fuji: '富士回遊', hokuto: '北斗', mizuho: 'みずほ', muroran: '室蘭本線', meitetsu: '名鉄', momotaro: '桃太郎', rinkai: 'りんかい線', rumoi: '留萌本線', 'red-arrow': 'レッドアロー', romancecar: 'ロマンスカー' });
const kana = c => c.replace(/[ぁ-ゖ]/g, x => String.fromCharCode(x.charCodeAt(0) + 0x60));
const smallKana = {ぁ:'ア',ぃ:'イ',ぅ:'ウ',ぇ:'エ',ぉ:'オ',ゃ:'ヤ',ゅ:'ユ',ょ:'ヨ',っ:'ツ'};
const spokenKana = c => c === 'ー' ? 'のばす音' : smallKana[c] ? `ちいさい、${smallKana[c]}` : kana(c);
Object.assign(names, { sunrise: 'サンライズ瀬戸・出雲', 'e4-max': 'E4系Max', haruka: '特急はるか', shiokaze: '特急しおかぜ', 'chuo-e233': '中央線' });
Object.assign(names, { oimachi: '大井町線', kaiji: 'かいじ', sunrise: 'サンライズ出雲', shimakaze: 'しまかぜ', 'spacia-x': 'スペーシアエックス', chiyoda: '千代田線', toyoko: '東横線', hanzomon: '半蔵門線', fukutoshin: '副都心線', laview: 'ラビュー', sotetsu: '相鉄線', nanbu: '南武線', hinotori: 'ひのとり', midosuji: '御堂筋線', yamabiko: 'やまびこ', yurikamome: 'ゆりかもめ' });
const add = (text, spoken = text) => lines.set(text, { text, spoken, file: createHash('sha256').update(text).digest('hex').slice(0, 16) + '.mp3' });
Object.assign(names, { sunrise: '寝台特急サンライズ瀬戸・出雲', 'e4-max': 'E4系Max', haruka: '特急はるか', shiokaze: '特急しおかぜ', 'chuo-e233': '中央線' });
Object.assign(names, { thunderbird: '特急サンダーバード', 'marine-liner': '快速マリンライナー', musashino: '武蔵野線', yokohama: '横浜線', ryomo: '特急りょうもう', minatomirai: 'みなとみらい線', 'kyoto-jr': 'JR京都線', sagano: '嵯峨野線' });
Object.assign(names, { 'tokiwa-express': '特急ときわ', sazanami: '特急さざなみ', 'shonan-express': '特急湘南', 'kusatsu-shima': '特急草津・四万', akagi: '特急あかぎ', revaty: '東武リバティ', 'romancecar-gse': 'ロマンスカーGSE', 'fujisan-view': '富士山ビュー特急' });
Object.assign(names, { 'shonan-shinjuku': '湘南新宿ライン' });
add(VOICE_SAMPLE);
Object.assign(names, Object.fromEntries(BOOK_TRAINS.map(train => [train.id, train.spokenName || train.bookName || train.name])));
add('おとが でるよ', '音が出るよ！');
add('できたね！');
for (const train of QUIZ_CARDS) {
  const name = train.kind ? train.name : names[train.id] || train.name;
  for (const letter of BASIC_KANA) {
    if (train.name.startsWith(letter) || (['を', 'ん'].includes(letter) && train.name.includes(letter)))
      add(tracePromptText(train, letter), `${name}の、${kana(letter)}。電車と一緒に、なぞってみよう。`);
  }
  add(train.name, name + '。');
  add(praiseText(train), `できたね！ ${name}！`);
  for (const letter of train.name) {
    add(questionText(train, letter), `${name}の、${spokenKana(letter)}。同じ文字は、どれかな？`);
    add(hintText(letter), `${spokenKana(letter)}を、探してみよう。`);
  }
}
for (const train of REWARD_TRAINS) add(rewardText(train), `${train.spokenName || names[train.id] || train.name}が、やってきた！`);
for (const c of KANA_ROWS.join('').replaceAll(' ', '')) {
  if (c === 'ー') add('のばす おと', 'のばす音。');
  else add(c, `${spokenKana(c)}。`);
}
try {
  const overrides = JSON.parse(await readFile('assets/voice/pronunciation-overrides.json', 'utf8'));
  for (const [text, spoken] of Object.entries(overrides)) {
    if (!lines.has(text)) throw new Error(`Unknown narration override: ${text}`);
    add(text, spoken);
  }
} catch (error) { if (error.code !== 'ENOENT') throw error; }
await mkdir('assets/voice', { recursive: true });
await writeFile('assets/voice/lines.json', JSON.stringify({ voice: 'ja-JP-NanamiNeural', rate: '-8%', pitch: '+3Hz', lines: [...lines.values()] }, null, 2) + '\n');
await writeFile('src/voice-manifest.js', `// Generated by scripts/voice-manifest.mjs\nexport const VOICE_FILES = ${JSON.stringify(Object.fromEntries([...lines.values()].map(l => [l.text, l.file])), null, 2)};\nexport const VOICE_SPOKEN = ${JSON.stringify(Object.fromEntries([...lines.values()].map(l => [l.text, l.spoken])), null, 2)};\n`);
console.log(`Prepared ${lines.size} voice lines.`);
